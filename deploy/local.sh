#!/usr/bin/env bash
# Run Orbit on your own network for testing. See docs/LOCAL_TESTING.md.
#   ./local.sh up      build and start (creates .env.local the first time)
#   ./local.sh ca      save the local certificate authority to orbit-local-ca.crt
#   ./local.sh logs    follow the server log
#   ./local.sh down    stop, keeping data
#   ./local.sh reset   stop and DELETE the local data and settings
set -euo pipefail
cd "$(dirname "$0")"
umask 077

compose() { docker compose --env-file .env.local -f docker-compose.yml -f docker-compose.local.yml "$@"; }
lan_ip() { ip -4 route get 1.1.1.1 | awk '{for (i = 1; i < NF; i++) if ($i == "src") print $(i + 1)}'; }
secret() { openssl rand -base64 "$1" | tr -d '\n'; }
setting() { sed -n "s/^$1=//p" .env.local; }

create_env() {
  local ip="${ORBIT_LAN_IP:-$(lan_ip)}"
  [ -n "$ip" ] || { echo "No network address found. Set ORBIT_LAN_IP and retry." >&2; exit 1; }
  cat > .env.local <<ENV
# Generated by local.sh for testing on your network. Not for the internet.
ORBIT_DOMAIN=$ip
ORBIT_BIND=$ip
ACME_EMAIL=local@example.com
PUBLIC_URL=https://$ip:8443
POSTGRES_PASSWORD=$(secret 24)
JWT_SECRET=$(secret 48)
SMTP_HOST=mailpit
SMTP_PORT=1025
SMTP_FROM=Orbit <orbit@example.com>
SMTP_ALLOW_PLAINTEXT=true
MAILPIT_PASSWORD=$(openssl rand -hex 8)
VAPID_SUBJECT=mailto:local@example.com
# Optional: GitHub sign-in. Callback: https://$ip:8443/api/auth/github/callback
GITHUB_CLIENT_ID=
GITHUB_CLIENT_SECRET=
ENV
  compose build orbit-server
  compose run --rm --no-deps -T orbit-server vapid-keys >> .env.local
}

case "${1:-}" in
  up)
    [ -f .env.local ] || create_env
    if [ "$(setting ORBIT_DOMAIN)" != "$(lan_ip)" ] && [ -z "${ORBIT_LAN_IP:-}" ]; then
      echo "Warning: this machine's address is now $(lan_ip), but .env.local has $(setting ORBIT_DOMAIN)." >&2
      echo "Run './local.sh reset' and 'up' again if devices can't connect." >&2
    fi
    compose up -d --build
    ip="$(setting ORBIT_DOMAIN)"
    cat <<INFO

Orbit        https://$ip:8443
Sign-in mail http://$ip:8025   (user: orbit  password: $(setting MAILPIT_PASSWORD))
Certificate  http://$ip:8081/ca.crt
INFO
    ;;
  ca)
    compose exec -T caddy cat /data/caddy/pki/authorities/local/root.crt > orbit-local-ca.crt
    chmod 644 orbit-local-ca.crt
    echo "Saved $(pwd)/orbit-local-ca.crt"
    ;;
  logs) compose logs -f orbit-server ;;
  down) compose down ;;
  reset)
    read -r -p "Delete the local Orbit database, certificate authority and .env.local? Type 'delete': " answer
    [ "$answer" = delete ] || { echo "Nothing removed."; exit 1; }
    compose down -v
    rm -f .env.local orbit-local-ca.crt
    ;;
  *) sed -n '2,8p' "$0"; exit 2 ;;
esac
